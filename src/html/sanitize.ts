import DOMPurify from 'dompurify'

const ALLOWED_TAGS = [
  'a',
  'abbr',
  'address',
  'article',
  'aside',
  'b',
  'blockquote',
  'br',
  'button',
  'caption',
  'cite',
  'code',
  'col',
  'colgroup',
  'dd',
  'div',
  'dl',
  'dt',
  'em',
  'figcaption',
  'figure',
  'footer',
  'form',
  'h1',
  'h2',
  'h3',
  'h4',
  'h5',
  'h6',
  'header',
  'hr',
  'i',
  'img',
  'input',
  'label',
  'li',
  'main',
  'nav',
  'ol',
  'optgroup',
  'option',
  'p',
  'picture',
  'pre',
  'section',
  'select',
  'small',
  'source',
  'span',
  'strong',
  'sub',
  'sup',
  'table',
  'tbody',
  'td',
  'textarea',
  'tfoot',
  'th',
  'thead',
  'tr',
  'ul',
  'video',
]

const ALLOWED_ATTR = [
  'alt',
  'class',
  'cols',
  'colspan',
  'controls',
  'disabled',
  'for',
  'height',
  'href',
  'id',
  'loop',
  'muted',
  'name',
  'placeholder',
  'playsinline',
  'poster',
  'readonly',
  'required',
  'role',
  'rows',
  'rowspan',
  'src',
  'target',
  'title',
  'type',
  'value',
  'width',
  'aria-label',
  'aria-hidden',
  'aria-describedby',
]

/** Sanitize AI / user HTML before iframe render. Drops script, handlers, inline style. */
export function sanitizeHtml(html: string): string {
  return DOMPurify.sanitize(html, {
    ALLOWED_TAGS,
    ALLOWED_ATTR,
    ALLOW_DATA_ATTR: true,
    ALLOW_UNKNOWN_PROTOCOLS: false,
    FORBID_TAGS: ['script', 'iframe', 'object', 'embed', 'link', 'meta', 'style', 'svg', 'math'],
    FORBID_ATTR: ['style', 'srcdoc'],
  })
}
